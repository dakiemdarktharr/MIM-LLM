"""Deterministic synthetic pilot; never treated as human-written test data.

The paired prompts differ in one factual time only. Propositions are stored
as structured obligations, not a single reference continuation.
"""

from __future__ import annotations

import json
import random
from itertools import pairwise
from pathlib import Path
from typing import Any

from .data import stable_split
from .oracle import delayed_power, execute_cabinet

NAMES = ("Lan", "Huy", "Mai", "An", "Binh", "Chi", "Dung", "Hoa")
OBJECTS = ("cabinet", "storage room", "medicine box", "archive")


def make_pair(
    pair_id: int, *, seed: int = 2026, overwrite_depth: int | None = None
) -> list[dict[str, Any]]:
    rng = random.Random((seed << 32) + pair_id)
    depth = overwrite_depth if overwrite_depth is not None else 2 + pair_id % 4
    if not 2 <= depth < len(NAMES):
        raise ValueError("overwrite_depth must be between 2 and 7")
    actors = rng.sample(NAMES, depth + 1)
    holder = actors[-1]
    obj = rng.choice(OBJECTS)
    transfers = " ".join(
        f"{source} passes the key to {target}." for source, target in pairwise(actors)
    )
    base = (
        f"The {obj} is locked. {actors[0]} holds the key. {transfers} "
        f"The rule says that at exactly 9:00 the key holder must open the {obj} if electricity has returned; "
        "if it is still out, the holder must wait. Electricity returns at {time}. "
        "Continue the scene in 3 to 5 sentences. Also explain what would be different if electricity returned ten minutes later."
    )
    pair = []
    for time in ("8:55", "9:05"):
        actual = execute_cabinet(actors, time)
        later = execute_cabinet(actors, delayed_power(time))
        pair.append(
            {
                "id": f"cabinet-{pair_id:04d}-{time.replace(':', '')}",
                "pair_id": f"cabinet-{pair_id:04d}",
                "source_id": f"cabinet-{pair_id:04d}",
                "split": stable_split(f"cabinet-{pair_id:04d}"),
                "premise_time": time,
                "condition_id": "base" if time == "8:55" else "perturbed",
                "changed_span": {"base": "8:55", "perturbed": "9:05"},
                "required_changed_predicates": [
                    "object_open_at_0900",
                    "holder_action_at_0900",
                ],
                "prompt": base.format(obj=obj, time=time),
                "overwrite_depth": depth,
                "facts_preserved": [
                    {"predicate": "key_holder_at_0900", "value": holder},
                    {"predicate": "key_transfer_chain", "value": actors},
                ],
                "actual_obligations": [
                    {
                        "predicate": "object_open_at_0900",
                        "value": actual.opened_at_0900,
                    },
                    {
                        "predicate": "holder_action_at_0900",
                        "value": actual.action_at_0900,
                    },
                ],
                "counterfactual_obligations": [
                    {"predicate": "power_time", "value": later.power_time},
                    {"predicate": "object_open_at_0900", "value": later.opened_at_0900},
                ],
                "relation_to_pair": "Only premise_time changes; holder and every transfer remain fixed. Opening at 9:00 must flip.",
                "origin": "synthetic pilot generated by this repository",
            }
        )
    return pair


def write_benchmark(path: str | Path, *, pairs: int = 100, seed: int = 2026) -> None:
    if pairs < 1:
        raise ValueError("pairs must be positive")
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        for index in range(pairs):
            for item in make_pair(index, seed=seed):
                handle.write(json.dumps(item, ensure_ascii=False) + "\n")


def write_demo_corpus(
    path: str | Path, *, stories: int = 500, seed: int = 2026
) -> None:
    """Self-created smoke corpus, not a substantive LM training dataset."""
    if stories < 20:
        raise ValueError("At least 20 stories needed for hashed splits")
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        for index in range(stories):
            scenario = make_pair(index, seed=seed)[index % 2]
            holder = scenario["facts_preserved"][0]["value"]
            time = scenario["premise_time"]
            obj = scenario["prompt"].split("The ", 1)[1].split(" is locked", 1)[0]
            action = (
                f"At 9:00, {holder} opens the {obj}."
                if time == "8:55"
                else f"At 9:00, {holder} waits, and the {obj} stays locked."
            )
            alternative = (
                f"If power had returned at 9:05, the {obj} would still be locked at 9:00."
                if time == "8:55"
                else f"If power had returned at 9:15, the {obj} would still be locked at 9:00."
            )
            text = scenario["prompt"] + "\n" + action + " " + alternative
            actors = scenario["facts_preserved"][1]["value"]
            transfer_ends = [
                text.index(f"passes the key to {actor}")
                + len(f"passes the key to {actor}")
                for actor in actors[1:]
            ]
            # Role label after consuming each byte: 0 original holder,
            # 1..depth the recipient of each transfer. EOS retains the state.
            states = (
                [0]
                + [
                    sum(pos + 1 >= end for end in transfer_ends)
                    for pos in range(len(text.encode("utf-8")))
                ]
                + [len(actors) - 1]
            )
            handle.write(
                json.dumps(
                    {
                        "source_id": f"demo-{index:04d}",
                        "split": stable_split(f"demo-{index:04d}"),
                        "text": text,
                        "state_labels": states,
                        "state_label_granularity": "utf8_byte",
                        "state_schema": "key_holder_role_index_0_to_5",
                        "origin": "self-created synthetic smoke data",
                    },
                    ensure_ascii=False,
                )
                + "\n"
            )
